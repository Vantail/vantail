/** Canonical names, for galleries and `<select>` demos. */
export const iconNames: readonly IconName[] = Object.keys(icons).sort() as IconName[];

/** Narrow an unknown string to a known icon name. */
export function isIconName(value: unknown): value is IconName {
  return typeof value === "string" && Object.hasOwn(icons, value);
}
